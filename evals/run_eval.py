"""Run the seeded-anomaly benchmark against the live agent (DESIGN.md milestone 5).

Usage (from the project root, ANTHROPIC_API_KEY in .env):

    python -m evals.run_eval

Runs every case in seed_anomalies.build_cases() through the real agent loop,
scores each against ground truth, prints a markdown results table, and saves it
to evals/results.md. No GCP needed — data is synthetic.
"""

import sys
from pathlib import Path

from anomaly_detector import get_client
from agent import run_remediation
from evals.seed_anomalies import build_cases, score_case

# Claude Haiku 4.5 pricing per million tokens
PRICE_IN = 1.00
PRICE_OUT = 5.00


def run() -> str:
    client = get_client()
    cases = build_cases()
    rows = []
    totals = {"seeded": 0, "verified": 0, "false_fixes": 0, "gave_up": 0, "cost": 0.0}

    for case in cases:
        print(f"Running case: {case['name']} ...", flush=True)
        report = run_remediation(case["df"], f"eval-{case['name']}", client)
        score = score_case(report, case["ground_truth"])
        usage = report.get("usage", {})
        cost = (usage.get("input_tokens", 0) * PRICE_IN + usage.get("output_tokens", 0) * PRICE_OUT) / 1e6

        totals["seeded"] += score["seeded"]
        totals["verified"] += score["verified"]
        totals["false_fixes"] += score["false_fixes"]
        totals["gave_up"] += score["gave_up"]
        totals["cost"] += cost

        rows.append(
            f"| {case['name']} | {score['seeded']} | {score['verified']} | {score['false_fixes']} "
            f"| {score['gave_up']} | {score['rows_retained']:.0%} | {score['attempts']} "
            f"| {score['turns']} | ${cost:.3f} |"
        )
        if score["collateral_anomalies"]:
            print(f"  WARNING collateral anomalies: {score['collateral_anomalies']}")

    success_rate = totals["verified"] / totals["seeded"] * 100 if totals["seeded"] else 0.0
    table = "\n".join([
        "| Case | Seeded | Verified fixes | False fixes | Gave up | Rows kept | Attempts | Turns | Cost |",
        "|---|---|---|---|---|---|---|---|---|",
        *rows,
        f"| **Total** | **{totals['seeded']}** | **{totals['verified']}** | **{totals['false_fixes']}** "
        f"| **{totals['gave_up']}** |  |  |  | **${totals['cost']:.3f}** |",
        "",
        f"**Fix success rate: {success_rate:.0f}%** "
        f"({totals['verified']}/{totals['seeded']} seeded anomalies verifiably fixed; "
        f"{totals['false_fixes']} false fixes, {totals['gave_up']} honest give-ups)",
    ])
    return table


def main() -> None:
    table = run()
    out = Path(__file__).parent / "results.md"
    out.write_text(f"# Seeded-anomaly eval results\n\nModel: claude-haiku-4-5 · generated by `python -m evals.run_eval`\n\n{table}\n", encoding="utf-8")
    print("\n" + table)
    print(f"\nSaved to {out}")


if __name__ == "__main__":
    sys.exit(main())
